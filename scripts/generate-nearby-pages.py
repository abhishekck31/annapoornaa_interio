"""
Regenerates lib/seo/nearby-pages.ts.

Usage (from the repo root):
  node scripts/dump-locality-pages.cjs > .nearby-pages.json
  python scripts/generate-nearby-pages.py .nearby-pages.json

For every locality page, lists the nearest pages of the same service (up to
four within 12 km), measured between locality centroids. Centroids come from
the GBA ward map (reports/seo-strategy-nov-2026/gba-ward-database.csv) where a
ward shares the locality's name, otherwise from MANUAL below.
"""

import csv, json, math, re, sys

MAX_LINKS, MAX_KM = 4, 12.0

# Localities with no GBA ward of the same name: approximate centroids.
MANUAL = {
    "BTM Layout": (12.9166, 77.6101),
    "Bagalur": (13.1350, 77.6680),
    "Bannerghatta Road": (12.8880, 77.5970),
    "Basavanagudi": (12.9406, 77.5738),
    "Brookefield": (12.9667, 77.7170),
    "CV Raman Nagar": (12.9850, 77.6630),
    "Devanahalli": (13.2470, 77.7120),
    "Electronic City": (12.8452, 77.6602),
    "Frazer Town": (12.9980, 77.6150),
    "Hesaraghatta Road": (13.0800, 77.5050),
    "Hoskote": (13.0707, 77.7982),
    "Kanakapura Road": (12.8800, 77.5450),
    "Kattigenahalli": (13.1150, 77.6350),
    "Koramangala": (12.9352, 77.6245),
    "Magadi Road": (12.9830, 77.5150),
    "Manyata Tech Park": (13.0450, 77.6200),
    "Old Airport Road": (12.9600, 77.6550),
    "Sahakar Nagar": (13.0620, 77.5880),
    "Sarjapur": (12.8600, 77.7860),
    "Sarjapur Road": (12.9100, 77.6850),
    "Vijayanagar": (12.9719, 77.5370),
}

# Hand-built location pages under app/ (not in any registry).
STATIC = [
    ("interior-designers-in-yelahanka", "Interior Designers in Yelahanka"),
    ("interior-designers-in-hsr-layout-bangalore", "Interior Designers in HSR Layout"),
    ("interior-designers-in-indiranagar-bangalore", "Interior Designers in Indiranagar"),
    ("interior-designers-in-jayanagar-bangalore", "Interior Designers in Jayanagar"),
    ("interior-designers-in-whitefield-bangalore", "Interior Designers in Whitefield"),
]

SERVICE = [
    (r"^(interior-designers|home-interior-design)-in-", "interior"),
    (r"^modular-kitchen-in-", "kitchen"),
    (r"^(house|turnkey|villa)-construction-in-", "construction"),
    (r"^home-renovation-in-", "renovation"),
    (r"^office-interior-design(ers)?-in-", "office"),
]


def norm(s):
    return re.sub(r"[^a-z]", "", s.lower().replace("ward", ""))


def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def main(path):
    wards = {}
    for w in csv.DictReader(open("reports/seo-strategy-nov-2026/gba-ward-database.csv", encoding="utf8")):
        wards.setdefault(norm(w["ward_name"]), (float(w["centroid_lat"]), float(w["centroid_lon"])))

    def centroid(place):
        if place in MANUAL:
            return MANUAL[place]
        n = norm(place)
        if n in wards:
            return wards[n]
        for k, v in wards.items():
            if k.startswith(n) or (n.startswith(k) and len(k) > 5):
                return v
        return None

    pages = [(p["slug"], p["label"]) for p in json.load(open(path, encoding="utf8")) if p["kind"] != "pillar"]
    pages += STATIC
    nodes, skipped = [], []
    for slug, label in pages:
        service = next((s for rx, s in SERVICE if re.match(rx, slug)), None)
        place = label.split(" in ")[-1]
        c = centroid(place) if place != "Bangalore" else None
        if service and c:
            nodes.append((slug, label, service, c))
        else:
            skipped.append(slug)

    out = {}
    for slug, label, service, c in nodes:
        near = sorted(
            (km(c, c2), s2, l2) for s2, l2, sv2, c2 in nodes if sv2 == service and s2 != slug and km(c, c2) <= MAX_KM
        )[:MAX_LINKS]
        if near:
            out[slug] = [(l2, s2) for _, s2, l2 in near]

    lines = [
        "/**",
        " * Nearby same-service pages for each locality page, used by the landing page",
        " * templates' \"Also serving nearby\" block.",
        " *",
        " * GENERATED by scripts/generate-nearby-pages.py — do not edit by hand. For each",
        f" * locality page, the nearest same-service pages, up to {MAX_LINKS} within {MAX_KM:g} km, using",
        " * GBA ward centroids (OpenCity, CC0; see reports/seo-strategy-nov-2026/) or an",
        " * approximate locality centroid where no ward shares the name.",
        " * Every href is checked against the live route list in lib/seo/routes.ts.",
        " */",
        "",
        "export const nearbyPages: Record<string, { label: string; href: string }[]> = {",
    ]
    for slug in sorted(out):
        lines.append(f'  "{slug}": [')
        for label, s2 in out[slug]:
            lines.append(f'    {{ label: "{label}", href: "/{s2}" }},')
        lines.append("  ],")
    lines.append("}")
    open("lib/seo/nearby-pages.ts", "w", encoding="utf8", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(out)} pages with nearby links; skipped (no service/centroid): {skipped}", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
